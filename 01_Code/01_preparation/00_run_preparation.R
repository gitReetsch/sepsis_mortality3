# ******************************************************************************
# 00_run_preparation.R
# ******************************************************************************
#
# Purpose: Run the data preparation scripts in the required order.
#
# - Load the project setup and data configuration.
# - Check the inputs and outputs required for the selected scripts.
# - Create the output folders and record the input inventory.
# - Run the selected preparation scripts and capture diagnostic output.
#
# Set the project root and selected scripts before running.
#
# Outputs:
# - path_common: shared FST files created by the selected preparation scripts:
#   discharges, diagnoses, procedures, icu, cod, and comorbidity_scores.
#   Filenames are generated by common_file() using start_year and end_year.
# - path_lookups: persistent lookup RDS files used and updated by GVS preparation.
# - path_output: a new run-specific folder under path_preparation_results,
#   containing input_inventory.csv, diagnostics.pdf, and validation reports.
#
# The run-specific validation outputs include:
# - validation_cod_linkage_<datestamp>.xlsx
# - validation_bevnat_cod_match_<datestamp>.png
#
# ******************************************************************************


# ******************************************************************************
# setup ----
# ******************************************************************************

# set paths
root <- "C:/dev/gitRepos/mortality"
code_dir <- file.path(normalizePath(getwd(), winslash="/", mustWork=TRUE), "01_Code")

# source setup and config
source(file.path(code_dir, "00_common", "02_setup.R"), local=TRUE)
source(file.path(code_dir, "00_common", "00_config_data.R"), local=TRUE)

# check for package comorbidity
if (!requireNamespace("comorbidity", quietly=TRUE)) stop("Missing package: comorbidity")


# ******************************************************************************
# check if files already exist ----
# ******************************************************************************
# Check that all raw input files exist
raw_inputs <- c(unlist(path_discharges), unlist(path_diagnoses), unlist(path_chop),
                unlist(path_icu_raw), path_cod)

if (any(!file.exists(raw_inputs))) stop("Missing raw inputs: ",
 paste(raw_inputs[!file.exists(raw_inputs)], collapse="; "))

# Check whether any expected output files already exist
overwrite_common <- FALSE # set to TRUE if you want to overwrite the 'output_paths_to_check' 
output_paths_to_check <- vapply(c("discharges","diagnoses","procedures","icu",
                                  "cod", "mortality_encounter",
                                  "comorbidity_scores"), common_file, character(1))

if (overwrite_common == FALSE && any(file.exists(output_paths_to_check))) {
   stop("Common outputs already exist. Review before setting overwrite_common=TRUE.")
}

# creates the shared data folder, path_common is defined in 00_config_data.R:
dir.create(path_common, recursive=TRUE, showWarnings=FALSE)
dir.create(path_lookups, recursive = TRUE, showWarnings = FALSE)
dir.create(path_preparation_results, recursive=TRUE, showWarnings=FALSE)

# tempfile() generates a unique output-folder name under path_preparation_results, 
# beginning with datestamp. The following dir.create() creates that folder.
path_output <- tempfile(pattern=paste0(datestamp,"_"), tmpdir=path_preparation_results)
dir.create(path_output)



# ******************************************************************************
# creates the input inventory ----
# ******************************************************************************
input_file_info <- file.info(raw_inputs)              # Get size and modification time for each input file

write.csv(                                            # Write the inventory as a CSV file
   data.frame(                                        # Assemble one row per input file
      path = raw_inputs,                              # Record the input file path
      bytes = input_file_info$size,                   # Record file size in bytes
      modified = as.character(input_file_info$mtime)  # Record modification time as text
   ),                                                 # Finish assembling the inventory data frame
   file.path(path_output, "input_inventory.csv"),     # Save it in this run's output folder
   row.names = FALSE                                  # Do not add row numbers as a column
)                                                     # Finish writing the CSV

# Capture diagnostic plots
pdf(file.path(path_output, "diagnostics.pdf"))        # Save plots sent to the active graphics device in this PDF

tryCatch(                                             # Ensure the PDF device is closed even if a script errors
   {                                                  # Begin the code to run
      for (script in c(                               # Loop over the preparation scripts in order
         "01_prepare_gvs.R",                          # Prepare GVS data
         "03_prepare_cod.R",                          # Prepare cause-of-death data
         "05_comorbidity.R",                          # Calculate comorbidity scores
         "06_validate.R"                              # Validate the prepared data
      )) {                                            # Finish the script list and begin the loop body
         message("Running ", script)                  # Print the script name to the console
         source(                                      # Run the current script
            file.path(code_dir, "01_preparation", script), # Build its path from the code directory and filename
            local = TRUE                              # Run it in the current environment so later scripts can use its objects
         )                                            # Finish running the current script
      }                                               # Finish looping over the scripts
   },                                                 # Finish the code block passed to tryCatch()
   finally = dev.off()                                # Close the PDF device, including if a script errors
)                                                     # Finish the tryCatch() call

message(                                              # Report where the run saved its outputs
   "Preparation finished. Common data: ",             # Begin the message with the shared-data location
   path_common,                                       # Add the shared-data folder path
   "; diagnostics: ",                                 # Add the diagnostics-folder label
   path_output                                        # Add the diagnostics folder path
) 